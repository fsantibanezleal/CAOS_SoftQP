"""Export every original timing cell as a LaTeX appendix table."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
EVIDENCE_COMMIT = "2d3f299d80edad49c2599e61bb6e3c875c119043"
EVIDENCE_PATH = "data/derived/experiments/campaign.json"
EVIDENCE_SHA256 = "3a79bc8abf63f70cac054c26bb5ec19bff0321e0047673d7bc3b239d380f00b5"
TARGET = HERE / "generated/timing-cells.tex"

SPLITS = {"development": "D", "heldout": "H", "robustness": "R"}
FAMILIES = {"asymmetric-elastic": "AE", "asymmetric-l1": "AL", "symmetric-elastic": "SE"}
METHODS = {
    "lifted": "Lifted OSQP",
    "generalized": "Gen. projection",
    "asymmetric": "Side-specific",
    "daqp": "DAQP",
    "flex": "FlexQP",
    "elastiqp": "ElastiQP",
}


def duration(cell):
    """Use the stored median and quartiles in the reader's millisecond units."""
    median = cell["median_seconds"]
    if median is None:
        return "N/A"
    lower = cell["quantile_25_seconds"]
    upper = cell["quantile_75_seconds"]
    return f"{1000 * median:.3f} [{1000 * lower:.3f}, {1000 * upper:.3f}]"


def render():
    evidence = subprocess.check_output(
        ["git", "show", f"{EVIDENCE_COMMIT}:{EVIDENCE_PATH}"], cwd=ROOT
    )
    if hashlib.sha256(evidence).hexdigest() != EVIDENCE_SHA256:
        raise ValueError("Original timing evidence differs from its committed SHA-256.")
    cells = json.loads(evidence)["cells"]
    header = r"Split & Family & Method & $n$ & Density & $\kappa$ & Median [IQR], ms & A / I \\"
    rows = [
        "% Generated by generate_timing_cells.py from the immutable original timing summary.",
        r"\begingroup\footnotesize\setlength{\tabcolsep}{3pt}",
        r"\begin{longtable}{@{}lllrrrlr@{}}",
        r"\caption{Complete original timing cells by split, penalty family, method, dimension, density and Hessian condition. Durations are stored medians and interquartile ranges, with accepted and incompatible measured counts retained.}\label{tab:timing-cells}\\",
        r"\toprule",
        header,
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        header,
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for cell in cells:
        counts = cell["counts"]
        if set(counts) - {"accepted", "incompatible"}:
            raise ValueError("Unexpected outcome state in the original timing summary.")
        fields = [
            SPLITS[cell["split"]],
            FAMILIES[cell["family"]],
            METHODS[cell["method"]],
            str(cell["n"]),
            f"{cell['density']:g}",
            str(cell["condition"]),
            duration(cell),
            f"{counts.get('accepted', 0)} / {counts.get('incompatible', 0)}",
        ]
        rows.append(" & ".join(fields) + r" \\")
    rows.extend([r"\end{longtable}", r"\endgroup"])
    return "\n".join(rows) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Refuse a stale table without writing it.")
    args = parser.parse_args()
    output = render()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != output:
            raise SystemExit("Original timing cell table differs from its committed evidence.")
    else:
        TARGET.write_text(output, encoding="utf-8", newline="\n")
    print("Original timing cell appendix matches committed evidence.")


if __name__ == "__main__":
    main()
